-- =============================================================================
-- WI-22 Interactive Analytics Benchmark -- 11: freeze the replay corpus
-- =============================================================================
-- Produces, for each of the 26 agent-emitted SQL blocks, three replay variants that differ
-- ONLY in the table name, plus a bind placeholder for account_id.
--
-- PARAMETERISATION DECISION (deliberately minimal):
--   * account_id -> `?`  (verified: exactly ONE occurrence in every one of the 26 blocks)
--   * date bounds LEFT EXACTLY AS THE AGENT WROTE THEM
--
-- Why not parameterise the dates too? Because the result cache is explicitly disabled
-- (USE_CACHED_RESULT = FALSE), value variation is not needed to prevent cache hits. What DOES
-- matter is account breadth, since that determines how much column data competes for the
-- interactive warehouse's cache. Rewriting the agent's date logic would risk changing query
-- semantics for no measurement benefit -- and the point of this corpus is that it is what the
-- agent actually emitted, not what I would have written.
--
-- Query SHAPE stability is preserved either way: each block is one fixed shape, so the
-- compiled-plan cache warms after its first execution. (18 blocks use DATEADD offsets and 22
-- contain hard date literals -- 70 date literals in total -- so shapes differ ACROSS blocks,
-- which is expected and fine; they must only be stable WITHIN a block.)
--
-- The trailing `/* Generated by Cortex */` marker is retained on purpose: Snowflake strips
-- LEADING comments from QUERY_TEXT but not trailing ones, so it survives into QUERY_HISTORY
-- and gives a free way to identify agent-derived queries.
-- =============================================================================

USE ROLE ACCOUNTADMIN;
USE WAREHOUSE COMPUTE_WH;

CREATE OR REPLACE TABLE IA_BENCH.BENCH.REPLAY_CORPUS AS
WITH base AS (
    SELECT
        q_id,
        block_seq,
        q_class,
        tier,
        account_id AS harvested_account_id,
        window_days,
        query_id   AS harvest_query_id,
        -- strip the trailing semicolon (and any trailing whitespace) so the text can be
        -- embedded in a template without terminating the statement early
        REGEXP_REPLACE(physical_sql, ';\\s*$', '') AS sql_raw
    FROM IA_BENCH.BENCH.AGENT_CORPUS
),
param AS (
    SELECT
        *,
        REGEXP_REPLACE(sql_raw, 'account_id\\s*=\\s*[0-9]+', 'account_id = ?') AS sql_param
    FROM base
)
SELECT
    q_id,
    block_seq,
    q_class,
    tier,
    harvested_account_id,
    window_days,
    harvest_query_id,
    1                                                                              AS param_count,
    sql_param                                                                      AS sql_clustered,
    REPLACE(sql_param, 'IA_BENCH.BENCH.FACT_CLUSTERED',
                       'IA_BENCH.BENCH.FACT_NONCLUSTERED')                         AS sql_nonclustered,
    REPLACE(sql_param, 'IA_BENCH.BENCH.FACT_CLUSTERED',
                       'IA_BENCH.BENCH.FACT_INTERACTIVE')                          AS sql_interactive
FROM param;

-- -----------------------------------------------------------------------------
-- Account pool for bind values.
-- Sampled FROM THE FACT TABLE so account frequency naturally follows the real power-law
-- skew (whales appear often, light accounts rarely) rather than a uniform draw, which would
-- misrepresent both cache behaviour and the latency tail.
-- -----------------------------------------------------------------------------
CREATE OR REPLACE TABLE IA_BENCH.BENCH.ACCOUNT_POOL AS
SELECT account_id, ROW_NUMBER() OVER (ORDER BY RANDOM()) AS pool_seq
FROM IA_BENCH.BENCH.FACT_CLUSTERED SAMPLE (200000 ROWS)
QUALIFY ROW_NUMBER() OVER (ORDER BY RANDOM()) <= 5000;

-- -----------------------------------------------------------------------------
-- Verify: substitution worked, all three variants differ only in table name
-- -----------------------------------------------------------------------------
SELECT
    COUNT(*)                                                          AS blocks,
    COUNT_IF(sql_clustered LIKE '%account_id = ?%')                   AS parameterised_ok,
    COUNT_IF(sql_clustered LIKE '%FACT_CLUSTERED%')                   AS points_at_clustered,
    COUNT_IF(sql_nonclustered LIKE '%FACT_NONCLUSTERED%')             AS points_at_nonclustered,
    COUNT_IF(sql_interactive LIKE '%FACT_INTERACTIVE%')               AS points_at_interactive,
    COUNT_IF(sql_clustered LIKE '%;%')                                AS still_has_semicolon,
    COUNT_IF(sql_clustered LIKE '%Generated by Cortex%')              AS marker_retained,
    COUNT_IF(REGEXP_COUNT(sql_clustered, '\\?') != 1)                 AS wrong_placeholder_count
FROM IA_BENCH.BENCH.REPLAY_CORPUS;

SELECT COUNT(*) AS pool_size, COUNT(DISTINCT account_id) AS distinct_accounts,
       MIN(account_id) AS min_acct, MAX(account_id) AS max_acct
FROM IA_BENCH.BENCH.ACCOUNT_POOL;
